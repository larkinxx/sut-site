// Отсев новостей до ИИ: то, что модель всё равно отбросит как «без практического значения для граждан и малого бизнеса»,
// не стоит запроса. Правила подобраны по истории content/raw (что ИИ пропускал, а что превращал в карточки)
// и нарочно осторожные: лучше лишний запрос, чем потерянная полезная новость. Проверка — scripts/news-filter.mjs --eval.
import fs from 'node:fs';
import path from 'node:path';

// Если в заголовке или начале текста есть что-то из этого — новость может касаться читателя, не отсеиваем
const USEFUL = /бизнес|лицензи|инвестор|крипт|налог|НДС|НДФЛ|УСН|самозанят|патент|вычет|пособи|пенси|МРОТ|зарплат|ипотек|кредит|вклад|депозит|ставк[аиу]|тариф|штраф|закон|Госдум|правительств|постановлени|маркировк|касс|ИП\b|малого бизнеса|МСП|предпринимател|банкрот|ЖКХ|коммунал|страхов|выплат|льгот|субсиди|маткапитал|материнск|ОСАГО|карт[аыу]\b|переводы?\b|СБП|мошенни|цифровой рубль|госуслуг/i;
// Чисто служебное и протокольное — отсеиваем, если нет признаков пользы выше
const NOISE = [
  [/аэропорт\S*.{0,40}(ограничени|прием|приём)|ограничени.{0,40}аэропорт/i, 'ограничения в аэропортах'],
  [/назначен\S* (гендиректор|генеральн|председател|президент|глав)|гендиректор\S* назначил|вернул\S* прежнего гендиректора|покинет пост|отставк/i, 'кадровые назначения'],
  [/дивиденд/i, 'дивиденды компаний'],
  [/монет[аеуы]|памятн\S* монет/i, 'памятные монеты'],
  [/совещани|семинар|квиз|рабочую встречу|провел\S* встречу|встретил\S* с|переговоры с/i, 'протокольные мероприятия'],
  [/индекс\S* (МосБиржи|РТС|IMOEX)|IMOEX|фондов\S* индекс|\bBrent\b|\bWTI\b|рубль (утром|днем|днём|вечером)|в начале (основных )?торгов|курс (евро|доллара|юаня) (ниже|выше)/i, 'биржевые сводки'],
  [/онлайн-урок|марафон|откроет свои двери|выпуск журнала|лауреат|видеообращени/i, 'просветительские и праздничные события'],
  [/купил\S* юан|продал\S* юан|операци\S* на валютном рынке по бюджетному правилу/i, 'операции ЦБ по бюджетному правилу']
];
// Зарубежное без связи с Россией
const ABROAD = /\b(США|ЕС|Евросоюз\S*|Брюссел\S*|Китай|Китая|КНР|Япони\S*|Инди[ия]|Турци\S*|Германи\S*|Франци\S*|Британи\S*|Лондон\S*|Вашингтон\S*|Пекин\S*|Киев\S*|Украин\S*|Белорусси\S*|Лукашенко|Сербии|Сербия|Вучич\S*|Ливи\S*|ОПЕК\S*|FT|Bloomberg|Reuters|WSJ|Euroclear|LVMH|Armani|Apple|Tesla|Nvidia)\b/;
const RUSSIA = /Росси|росси|рубл|₽|ЦБ\b|Банк России|Минфин|ФНС|Госдум|в РФ|РФ\b|российск/;

export function preSkip(raw) {
  const head = `${raw.title || ''} ${String(raw.text || '').slice(0, 300)}`;
  if (USEFUL.test(head)) return null;
  for (const [re, why] of NOISE) if (re.test(raw.title || '')) return why;
  if (ABROAD.test(raw.title || '') && !RUSSIA.test(head)) return 'зарубежная новость без связи с Россией';
  return null;
}

// Проверка на истории: node scripts/news-filter.mjs --eval
if (import.meta.url === `file://${process.argv[1]}` && process.argv.includes('--eval')) {
  const dir = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'content', 'raw');
  let caught = 0, skipped = 0, wrong = [];
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.json'))) {
    const r = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    if (!r.drafted) continue;
    const why = preSkip(r);
    if (r.skipReason) { skipped++; if (why) caught++; } else if (why) wrong.push(`${why}: ${r.title}`);
  }
  console.log(`ИИ пропустил ${skipped}, фильтр поймал бы ${caught} (${Math.round((caught / Math.max(skipped, 1)) * 100)}%). Ошибочно отсеял бы полезных: ${wrong.length}`);
  wrong.forEach((w) => console.log('  ', w));
  process.exit(wrong.length ? 1 : 0);
}
